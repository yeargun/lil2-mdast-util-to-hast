// Generates src/jsx/properties.lil from property-information and hast-util-to-jsx-runtime's rules: for every
// hast property the family creates (`propNames` in src/hast/hast.lil, by prop id), its React prop key
// in the html and svg schemas, and whether a list value is comma-separated.
import {readFileSync, writeFileSync} from 'node:fs'
import {createRequire} from 'node:module'
import {pathToFileURL} from 'node:url'
const require = createRequire(import.meta.url)
const pi = await import(pathToFileURL(require.resolve('property-information')).href)
const version = JSON.parse(readFileSync(new URL('../node_modules/property-information/package.json', import.meta.url), 'utf8')).version
const source = readFileSync(new URL('../src/hast/hast.lil', import.meta.url), 'utf8')
const propNames = JSON.parse(source.match(/export string\[\] propNames = (\[.*\]);/)[1])
// hast-util-to-jsx-runtime `createProperty` with `elementAttributeNameCase: 'react'`.
const key = (schema, prop) => { const info = pi.find(schema, prop); return info.space ? (pi.hastToReact[info.property] || info.property) : info.attribute }
const comma = (schema, prop) => Boolean(pi.find(schema, prop).commaSeparated)
const props = propNames.slice(1)
const html = props.map(p => key(pi.html, p)), svg = props.map(p => key(pi.svg, p))
const commaHtml = props.map(p => comma(pi.html, p)), commaSvg = props.map(p => comma(pi.svg, p))
const list = a => '[' + ['', ...a].map(v => JSON.stringify(v)).join(', ') + ']'
const bools = a => '[' + [false, ...a].join(', ') + ']'
const same = (a, b) => a.every((v, i) => v === b[i])
writeFileSync(new URL('../src/hast/properties.lil', import.meta.url), `// property-information ${version} and hast-util-to-jsx-runtime: the JSX prop key of each core hast property (by
// prop id, see \`propNames\` in hast.lil) in the html and svg schemas, and whether its list value is comma-separated.
// Layers that create more properties append to these through \`defineProp\`. Generated by scripts/generate-properties.mjs.

export string[] propReact = ${list(html)};
export string[] propReactSvg = ${list(svg)};
export bool[] propComma = ${bools(commaHtml)};
export bool[] propCommaSvg = ${bools(commaSvg)};
`)
console.log(props.length, 'properties; svg keys', same(html, svg) ? 'equal html' : 'differ', '; comma', commaHtml.filter(Boolean).length)
